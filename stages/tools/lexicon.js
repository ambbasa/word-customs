function hasBatchim(s) { const c = s.charCodeAt(s.length - 1); if (c < 0xAC00 || c > 0xD7A3) return false; return (c - 0xAC00) % 28 !== 0; }
function isRieul(s) { const c = s.charCodeAt(s.length - 1); return c >= 0xAC00 && c <= 0xD7A3 && (c - 0xAC00) % 28 === 8; }
function nounForms(n) {
  const ps = hasBatchim(n) ? PARTICLES_C.map(p => (p === '으로' && isRieul(n)) ? '로' : p) : PARTICLES_V;
  return [n, ...ps.map(p => n + p)];
}
function josa(n, pair) { // pair '을/를' 등 — 앞=받침 있음
  const [a, b] = pair.split('/');
  if (pair === '으로/로') return n + ((hasBatchim(n) && !isRieul(n)) ? '으로' : '로');
  return n + (hasBatchim(n) ? a : b);
}

