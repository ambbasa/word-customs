function isActive(term, day, phase) {
  const t = TERMS[term];
  if (day < t.from) return false;
  if (day === t.from && t.fromPhase === 'after' && phase !== 'after') return false;
  if (term === '감정어') return true;
  return true;
}
function emotionMembers(day, phase) {
  const m = TERMS['감정어'].members.slice();
  if (day > 17 || (day === 17 && phase === 'after')) return m.filter(x => x !== '그리움');
  return m;
}
function baseL(term, day, phase) {
  const g = TERMS[term].grade;
  const d30after = day === 30 && phase === 'after';
  if (g === 1) return d30after ? 60 : (day <= 11 ? 70 : 65);
  if (g === 2) { if (day === 30) return phase === 'after' ? 67 : 72; if (day === 29 && phase === 'after') return 72; return 75; }
  return d30after ? 80 : 85; // 3등급·감정어
}
function effL(term, day, phase, origin) {
  let L = baseL(term, day, phase);
  if (day >= 7 && day <= 19 && origin === '제3구역' && term !== '감정어') L -= 10; // R06: 통제 어휘(W)만, 감정어 허가 경계 제외 (FIXLIST ① 기획 결정)
  return L;
}
function activeTerms(day, phase) { return Object.keys(TERMS).filter(t => isActive(t, day, phase)); }

